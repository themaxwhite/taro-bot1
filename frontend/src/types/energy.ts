/**
 * Энергия — валюта разблокировок. Одна единица открывает расклад
 * (карты вместе с толкованием), дополнительную карту или уточняющий
 * вопрос.
 *
 * Цены задаёт backend (app/energy.py::ENERGY_PACKS) — здесь только то,
 * что нужно нарисовать выбор. Держать синхронно с тем файлом.
 */
export interface EnergyPack {
  id: string;
  title: string;
  amount: number;
  priceRub: number;
  badge: string | null;
}

/** Из чего складывается баланс — показывается подсказкой в профиле. */
export interface EnergyBreakdown {
  /** Всего доступно разблокировок прямо сейчас, по всем источникам. */
  balance: number;
  /** Бесплатная суточная энергия, ещё не потраченная сегодня. */
  daily: number;
  /** Сколько её начисляется в сутки — ёмкость суточной зарядки. */
  dailyMax: number;
  /** Купленная пакетом — не сгорает. */
  purchased: number;
  /** Заработанная приглашениями. */
  referral: number;
  /**
   * Остаток и ёмкость месячной квоты подписки; null, если подписки нет.
   *
   * Единственный источник энергии с настоящим потолком — поэтому именно
   * он и рисуется шкалой аккумулятора. Купленная и реферальная копятся
   * без предела, у них знаменателя не существует.
   */
  subscription: { remaining: number; total: number } | null;
}
