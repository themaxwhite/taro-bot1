// Общая для всех иконок карта: скруглённый прямоугольник в пропорции
// настоящей карты. Один примитив на весь набор — этим и держится стиль.
function Card({ x, y, w = 4.6, h = 7, rotate }: { x: number; y: number; w?: number; h?: number; rotate?: number }) {
  return (
    <rect
      x={x}
      y={y}
      width={w}
      height={h}
      rx="0.9"
      transform={rotate ? `rotate(${rotate} ${x + w / 2} ${y + h / 2})` : undefined}
    />
  );
}

function Icon({ children }: { children: React.ReactNode }) {
  return (
    <svg
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth="1.15"
      strokeLinecap="round"
      strokeLinejoin="round"
      width="100%"
      height="100%"
      aria-hidden="true"
    >
      {children}
    </svg>
  );
}

