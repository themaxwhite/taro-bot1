def fallback_interpretation(card_names: list[str], spread_title: str) -> str:
    cards = ", ".join(card_names)
    return (
        f"Расклад «{spread_title}» — {cards}. "
        "Подробное AI-толкование сейчас недоступно (не настроен ключ AI-сервиса "
        "на сервере), но сочетание этих карт стоит воспринимать как единую историю: "
        "обратите внимание, какие чувства каждая карта вызывает у вас лично — "
        "в этом чаще всего и есть самая точная подсказка."
    )


