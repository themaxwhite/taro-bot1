"""
Энергия — валюта разблокировок.

Одна единица открывает одно из: расклад целиком (карты вместе с
толкованием), дополнительную карту или уточняющий вопрос. Подписка даёт
свой месячный запас разблокировок; энергию можно докупить пакетом, и она,
в отличие от подписки, не сгорает.

Цены пакетов держим синхронно с frontend/src/types/energy.ts.
"""

from dataclasses import dataclass


@dataclass(frozen=True)
class EnergyPack:
    id: str
    title: str
    amount: int
    price_rub: int
    # Маркетинговая плашка на карточке пакета, на поведение не влияет.
    badge: str | None = None

    @property
    def price_per_unit(self) -> float:
        return self.price_rub / self.amount


# Пакет намеренно дороже подписки в пересчёте на единицу: самый выгодный
# пакет — 11,2 руб. за штуку против 8,56 даже в самом невыгодном по
# единице тарифе («Плюс») и 4,00 в «Магистре». Пакет
# продаёт не цену, а отсутствие ежемесячного списания: разово докупить и
# забыть. Если сделать его дешевле подписки, подписку не купит никто —
# энергия ведь ещё и не сгорает.
ENERGY_PACKS: dict[str, EnergyPack] = {
    "small": EnergyPack(id="small", title="5 энергии", amount=5, price_rub=89),
    "medium": EnergyPack(id="medium", title="15 энергии", amount=15, price_rub=199, badge="Выгодно"),
    "large": EnergyPack(id="large", title="40 энергии", amount=40, price_rub=449, badge="Максимум"),
}

# Бесплатная энергия, начисляемая раз в календарные сутки (UTC) и не
# переносящаяся на завтра. Намеренно держится ниже даже дневного темпа
# «Базового» тарифа — это повод вернуться завтра, а не замена подписке.
# Карта дня её не тратит: она бесплатна сама по себе.
DAILY_FREE_ENERGY = 1


# Цена одного вопроса таролога в чате. Дороже расклада намеренно: расклад
# отвечает по разложенным картам, а чат отвечает на что угодно, помнит
# разговор и держит контекст прошлых раскладов.
#
# Следствие, которое надо держать в голове при изменении числа: суточная
# бесплатная энергия не копится (она перезаписывается, см. комментарий к
# DAILY_FREE_ENERGY), поэтому любая цена выше 1 закрывает чат для того,
# кто живёт только на суточных начислениях. Дойти до пяти можно
# подпиской, пакетом или рефералами — это осознанная граница, а не
# побочный эффект.
CHAT_QUESTION_COST = 5
