def _build_minor_meanings() -> dict[str, tuple[str, str]]:
    result: dict[str, tuple[str, str]] = {}
    for rank_id, per_suit in _MINOR_MEANINGS.items():
        for suit_id, meaning in per_suit.items():
            result[f"minor-{suit_id}-{rank_id}"] = meaning
    return result


MINOR_MEANINGS: dict[str, tuple[str, str]] = _build_minor_meanings()

ALL_MEANINGS: dict[str, tuple[str, str]] = {**MAJOR_MEANINGS, **MINOR_MEANINGS}

assert len(ALL_MEANINGS) == 78, f"Expected 78 card meanings, got {len(ALL_MEANINGS)}"


def meaning_for(card_id: str, is_reversed: bool) -> str:
    upright, reversed_ = ALL_MEANINGS[card_id]
    return reversed_ if is_reversed else upright
