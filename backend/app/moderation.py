"""
Проверка вопроса пользователя к раскладу.

Список тем совпадает с разделом «О чём нельзя спрашивать» в условиях
использования (frontend/src/pages/TermsScreen/TermsScreen.tsx) — правило,
о котором нельзя прочитать в условиях, выглядит как произвол, поэтому
менять одно без другого нельзя.

Проверка нарочно грубая и локальная: без обращения к модели. Вопрос
проверяется на каждом розыгрыше расклада, и лишний сетевой вызов туда
добавил бы и задержку, и стоимость, и ещё одну причину для отказа. Цена
такого решения — отсекаются формулировки, а не намерения: обойти набор
слов несложно. Это осознанный размен, а не недосмотр: задача — не
пропускать очевидно неуместные вопросы и внятно объяснять почему, а не
строить настоящую модерацию.

Основа сравнения — начало слова: русский язык словоизменительный, и
«политика», «политике», «политический» это одна основа. Короткие и
многозначные основы задаются целыми словами (WORDS), иначе «бог» поймает
«богатство», а «рак» — «характер».
"""

import re
from dataclasses import dataclass, field


@dataclass(frozen=True)
class Topic:
    id: str
    # Что показать пользователю, если вопрос попал в эту тему.
    message: str
    # Основы: совпадение с началом слова в любой форме.
    stems: tuple[str, ...] = ()
    # Целые слова: только точное совпадение, для коротких и многозначных.
    words: tuple[str, ...] = field(default=())


TOPICS: tuple[Topic, ...] = (
    Topic(
        id="politics",
        message="Не гадаем на политику — выборы, власть, войну и всё вокруг них.",
        stems=(
            "политик", "политич", "выбор", "президент", "депутат", "правительств",
            "оппозици", "митинг", "санкци", "мобилизац", "governmen",
        ),
        words=("война", "войны", "войне", "войну", "войной", "власть", "власти"),
    ),
    Topic(
        id="religion",
        message="Не гадаем на религию и веру — это не то, что стоит доверять картам.",
        stems=(
            "религи", "церков", "христиан", "мусульман", "ислам", "иуде", "будди",
            "молитв", "священник", "батюшк", "намаз", "крещен",
        ),
        words=("бог", "бога", "богу", "богом", "боге", "грех", "греха", "аллах", "аллаха"),
    ),
    Topic(
        id="health",
        message="Не ставим диагнозов и не гадаем на здоровье — с этим к врачу, а не к картам.",
        stems=(
            "диагноз", "опухол", "онколог", "беременн", "лекарств", "таблетк",
            "симптом", "анализы", "операци", "психиатр", "антидепрессант",
        ),
        words=("рак", "рака", "болезнь", "болезни", "лечение", "лечения"),
    ),
    Topic(
        id="death",
        message="Не гадаем на смерть — ни свою, ни чужую.",
        stems=("смерт", "умру", "умрёт", "умрет", "погибн", "суицид", "самоубий", "похорон"),
    ),
    Topic(
        id="illegal",
        message="Не гадаем на противоправное.",
        stems=("наркотик", "украст", "воровств", "взлом", "мошенн", "отмыв", "контрабанд"),
        words=("убить", "убью", "оружие", "оружия"),
    ),
)

# ё и е в пользовательском вводе взаимозаменяемы, регистр не важен,
# всё кроме букв и цифр считаем разделителем.
_SPLIT = re.compile(r"[^0-9a-zа-я]+")


def _normalize(text: str) -> list[str]:
    return [w for w in _SPLIT.split(text.lower().replace("ё", "е")) if w]


def find_violation(question: str) -> Topic | None:
    """Первая тема, под которую попадает вопрос, или None."""
    words = _normalize(question)
    if not words:
        return None

    for topic in TOPICS:
        normalized_words = {w.replace("ё", "е") for w in topic.words}
        if normalized_words & set(words):
            return topic
        for stem in topic.stems:
            stem = stem.replace("ё", "е")
            if any(w.startswith(stem) for w in words):
                return topic
    return None


class QuestionNotAllowed(Exception):
    """Вопрос попал под одно из ограничений. Несёт готовый текст для пользователя."""

    def __init__(self, topic: Topic) -> None:
        super().__init__(topic.message)
        self.topic = topic


def ensure_question_allowed(question: str) -> None:
    """
    Отклоняет вопрос с 400 и объяснением, если он попал под ограничение.

    Живёт здесь, а не в слое API, чтобы правило и его применение нельзя
    было развести по разным файлам: любой новый эндпоинт, принимающий
    вопрос от пользователя, зовёт эту функцию.
    """
    from fastapi import HTTPException

    topic = find_violation(question)
    if topic is not None:
        raise HTTPException(status_code=400, detail=topic.message)
